type decision struct {
	cx  int
	bit int
}

func genDecisions(rng *rand.Rand, n, nctx int, bias float64) []decision {
	ds := make([]decision, n)
	for i := range ds {
		cx := rng.IntN(nctx)
		p := bias
		if cx%2 == 1 {
			p = 0.5
		}
		b := 0
		if rng.Float64() >= p {
			b = 1
		}
		ds[i] = decision{cx, b}
	}
	return ds
}

func encodeAll(ds []decision, nctx int) []byte {
	e := NewEncoder()
	cxs := make([]Context, nctx)
	for _, d := range ds {
		e.Encode(&cxs[d.cx], d.bit)
	}
	return append([]byte(nil), e.Flush()...)
}

func TestRoundTrip(t *testing.T) {
	rng := rand.New(rand.NewPCG(1, 2))
	for _, bias := range []float64{0.5, 0.9, 0.999, 0.99999, 1.0} {
		for _, n := range []int{0, 1, 2, 7, 100, 1000, 10000} {
			nctx := 1 + rng.IntN(8)
			ds := genDecisions(rng, n, nctx, bias)
			data := encodeAll(ds, nctx)
			dec := NewDecoder(data)
			cxs := make([]Context, nctx)
			for i, d := range ds {
				if got := dec.Decode(&cxs[d.cx]); got != d.bit {
					t.Fatalf("bias %g n %d: decision %d: got %d, want %d", bias, n, i, got, d.bit)
				}
			}
		}
	}
}

func TestRoundTripInitialStates(t *testing.T) {
	rng := rand.New(rand.NewPCG(3, 4))
	ds := genDecisions(rng, 5000, 3, 0.95)
	init := [3][2]uint8{{46, 0}, {3, 0}, {4, 1}}
	e := NewEncoder()
	var ec [3]Context
	for i := range ec {
		ec[i].Reset(init[i][0], init[i][1])
	}
	for _, d := range ds {
		e.Encode(&ec[d.cx], d.bit)
	}
	dec := NewDecoder(e.Flush())
	var dc [3]Context
	for i := range dc {
		dc[i].Reset(init[i][0], init[i][1])
	}
	for i, d := range ds {
		if got := dec.Decode(&dc[d.cx]); got != d.bit {
			t.Fatalf("decision %d: got %d, want %d", i, got, d.bit)
		}
	}
}

// maxIndexAfter encodes ds in nctx contexts and returns the largest
// probability state index observed in any context during coding.
func maxIndexAfter(ds []decision, nctx int) uint8 {
	e := NewEncoder()
	cxs := make([]Context, nctx)
	var maxIdx uint8
	for _, d := range ds {
		e.Encode(&cxs[d.cx], d.bit)
		maxIdx = max(maxIdx, cxs[d.cx].index)
	}
	return maxIdx
}

func TestReachesLastState(t *testing.T) {
	// a long run of one symbol must drive the state machine up to the
	// last adaptive state (45), and the round trip must still hold
	var ds []decision
	for range 20000 {
		ds = append(ds, decision{0, 0})
	}
	if got := maxIndexAfter(ds, 1); got != 45 {
		t.Fatalf("max state index %d, want 45", got)
	}
	for i := range 200 {
		ds = append(ds, decision{0, i % 2})
	}
	data := encodeAll(ds, 1)
	dec := NewDecoder(data)
	var cx Context
	for i, d := range ds {
		if got := dec.Decode(&cx); got != d.bit {
			t.Fatalf("decision %d: got %d, want %d", i, got, d.bit)
		}
	}
}

