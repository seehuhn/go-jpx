func TestKnownAnswer(t *testing.T) {
	rng := rand.New(rand.NewPCG(11, 12))
	ds := make([]decision, 2000)
	for i := range ds {
		cx := rng.IntN(4)
		bit := 0
		if rng.Float64() < 0.8 {
			bit = 1
		}
		ds[i] = decision{cx, bit}
	}

	data := encodeAll(ds, 4)
	if got := hex.EncodeToString(data); got != knownAnswerHex {
		t.Fatalf("encoded data %s, want %s", got, knownAnswerHex)
	}

	want, err := hex.DecodeString(knownAnswerHex)
	if err != nil {
		t.Fatal(err)
	}
	dec := NewDecoder(want)
	var cxs [4]Context
	for i, d := range ds {
		if got := dec.Decode(&cxs[d.cx]); got != d.bit {
			t.Fatalf("decision %d: got %d, want %d", i, got, d.bit)
		}
	}
}

func TestNoMarkerInOutput(t *testing.T) {
	rng := rand.New(rand.NewPCG(5, 6))
	for trial := range 200 {
		n := rng.IntN(5000)
		bias := []float64{0.5, 0.8, 0.99}[trial%3]
		data := encodeAll(genDecisions(rng, n, 4, bias), 4)
		for i := 1; i < len(data); i++ {
			if data[i-1] == 0xFF && data[i] >= 0x90 {
				t.Fatalf("trial %d: marker %02x%02x at %d", trial, data[i-1], data[i], i-1)
			}
		}
		if len(data) > 0 && data[len(data)-1] == 0xFF {
			t.Fatalf("trial %d: output ends in 0xFF", trial)
		}
	}
}

func TestDecodePastEnd(t *testing.T) {
	for _, data := range [][]byte{nil, {}, {0x00}, {0x55}, {0xFF}} {
		dec := NewDecoder(data)
		var cxs [4]Context
		for i := range 5000 {
			dec.Decode(&cxs[i%4])
		}
	}

	// decoding the same truncated data twice must give the same bits
	rng := rand.New(rand.NewPCG(13, 14))
	ds := genDecisions(rng, 20000, 1, 0.5)
	full := encodeAll(ds, 1)
	for _, k := range []int{len(full) - 1, len(full) - 2, len(full) / 2} {
		trunc := full[:k]
		run := func() []int {
			dec := NewDecoder(trunc)
			var cx Context
			bits := make([]int, len(ds))
			for i := range bits {
				bits[i] = dec.Decode(&cx)
			}
			return bits
		}
		first, second := run(), run()
		if diff := cmp.Diff(first, second); diff != "" {
			t.Fatalf("k=%d: decoding is not deterministic (-first +second):\n%s", k, diff)
		}

		// with an unbiased source each decision costs about 1.05 bits, so
		// the first (8k-64)/1.1 decisions are determined by the k bytes
		n := (8*k - 64) * 10 / 11
		if n > len(ds) {
			t.Fatalf("k=%d: test needs more decisions", k)
		}
		for i := range n {
			if first[i] != ds[i].bit {
				t.Fatalf("k=%d: decision %d: got %d, want %d", k, i, first[i], ds[i].bit)
			}
		}
	}
}

func TestZeroContext(t *testing.T) {
	var a, b Context
	b.Reset(0, 0)
	if a != b {
		t.Error("zero context differs from state 0, mps 0")
	}
	e := NewEncoder()
	for _, bit := range []int{0, 1, 1, 0, 0, 0, 1} {
		e.Encode(&a, bit)
	}
	dec := NewDecoder(e.Flush())
	for i, want := range []int{0, 1, 1, 0, 0, 0, 1} {
		if got := dec.Decode(&b); got != want {
			t.Fatalf("decision %d: got %d, want %d", i, got, want)
		}
	}
}

func TestResetReuse(t *testing.T) {
	rng := rand.New(rand.NewPCG(7, 8))
	e := NewEncoder()
	dec := &Decoder{}
	for range 5 {
		ds := genDecisions(rng, 1000, 2, 0.9)
		var cxs [2]Context
		for _, d := range ds {
			e.Encode(&cxs[d.cx], d.bit)
		}
		if e.Len() == 0 {
			t.Error("no bytes emitted")
		}
		dec.Init(e.Flush())
		cxs = [2]Context{}
		for i, d := range ds {
			if got := dec.Decode(&cxs[d.cx]); got != d.bit {
				t.Fatalf("decision %d: got %d, want %d", i, got, d.bit)
			}
		}
		e.Reset()
	}
}

func benchDecisions() []decision {
	return genDecisions(rand.New(rand.NewPCG(9, 10)), 1<<20, 16, 0.9)
}

func BenchmarkEncode(b *testing.B) {
	ds := benchDecisions()
	e := NewEncoder()
	var cxs [16]Context
	b.ReportAllocs()
	for b.Loop() {
		e.Reset()
		for _, d := range ds {
			e.Encode(&cxs[d.cx], d.bit)
		}
		e.Flush()
	}
}

func BenchmarkDecode(b *testing.B) {
	ds := benchDecisions()
	data := encodeAll(ds, 16)
	dec := &Decoder{}
	var cxs [16]Context
	b.ReportAllocs()
	for b.Loop() {
		dec.Init(data)
		for _, d := range ds {
			dec.Decode(&cxs[d.cx])
		}
	}
}
